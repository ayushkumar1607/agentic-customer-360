def check_imports(r: Report):
    r.section("Python Imports")
    for mod in MODULES:
        try:
            importlib.import_module(mod)
            r.ok(mod)
        except Exception as e:
            r.fail(mod, f"{type(e).__name__}: {e}")


def check_contracts(r: Report):
    r.section("Class / Function Contracts")
    for mod_name, symbols in CONTRACTS:
        try:
            mod = importlib.import_module(mod_name)
        except Exception as e:
            r.fail(mod_name, f"cannot import: {e}")
            continue
        for sym in symbols:
            if hasattr(mod, sym):
                r.ok(f"{mod_name}.{sym}")
            else:
                r.fail(f"{mod_name}.{sym}", "MISSING")


# ---------- section 3: config ----------------------------------------------

def check_config(r: Report):
    r.section("Configuration")
    try:
        from config.settings import settings
        r.ok(f"settings loaded, fast={settings.groq_model_fast}")
        for key in ("groq_api_key", "groq_model_fast", "groq_model_reason",
                    "groq_model_alt", "memory_decay_lambda"):
            if getattr(settings, key, None) is not None:
                r.ok(f"settings.{key}")
            else:
                r.fail(f"settings.{key}", "not set")
        if not settings.groq_api_key or settings.groq_api_key.startswith("your_"):
            r.warn("GROQ_API_KEY", "placeholder — needed for live pipeline runs")
    except Exception as e:
        r.fail("config.settings", f"{e}")

    try:
        from src.guardrails.scanner import GuardrailScanner
        s = GuardrailScanner()
        rules = list(s._rules.keys())
        if rules:
            r.ok(f"guardrails loaded, {len(rules)} rules: {rules}")
        else:
            r.fail("guardrails.yaml", "zero rules loaded")
    except Exception as e:
        r.fail("guardrails.yaml", f"{e}")

    try:
        import yaml
        with open(_ROOT / "config" / "agents.yaml", encoding="utf-8") as f:
            agents = (yaml.safe_load(f) or {}).get("agents", {})
        if agents:
            r.ok(f"agents.yaml loaded, {len(agents)} entries")
        else:
            r.fail("agents.yaml", "no 'agents' key")
    except Exception as e:
        r.fail("agents.yaml", f"{e}")


# ---------- section 4: artifacts -------------------------------------------

def check_artifacts(r: Report):
    r.section("Generated Artifacts")

    jsonl = _ROOT / "output" / "inferred-events.jsonl"
    if jsonl.exists() and jsonl.stat().st_size > 0:
        try:
            lines = [json.loads(l) for l in jsonl.read_text(encoding="utf-8").splitlines() if l.strip()]
            r.ok(f"inferred-events.jsonl: {len(lines)} checkpoints")
            required = {"as_of_time", "inferred_state", "confidence_band",
                        "action", "hitl_status"}
            for i, cp in enumerate(lines):
                missing = required - set(cp.keys())
                if missing:
                    r.fail(f"checkpoint {i}", f"missing fields: {missing}")
                else:
                    r.ok(f"checkpoint {i}: state={cp['inferred_state']}, "
                         f"action={cp['action']}, hitl={cp['hitl_status']}")
        except Exception as e:
            r.fail("inferred-events.jsonl", f"parse error: {e}")
    else:
        r.warn("inferred-events.jsonl", "not generated — run pipeline")

    rep = _ROOT / "output" / "evaluation_report.json"
    if rep.exists() and rep.stat().st_size > 0:
        try:
            data = json.loads(rep.read_text(encoding="utf-8"))
            r.ok(f"evaluation_report.json: overall_accuracy={data.get('overall_accuracy')}")
        except Exception as e:
            r.fail("evaluation_report.json", f"parse error: {e}")
    else:
        r.warn("evaluation_report.json", "not generated — run evaluation")


# ---------- section 5: docs ------------------------------------------------

DOC_MIN_BYTES = 400   # below this is suspicious for our docs

def check_docs(r: Report):
    r.section("Documentation Content")
    for doc in ["README.md", "docs/research_log.md",
                "docs/solution_document.md", "docs/evaluation_report.md"]:
        p = _ROOT / doc
        if not p.exists():
            r.fail(doc, "MISSING")
            continue
        size = p.stat().st_size
        if size < DOC_MIN_BYTES:
            r.warn(doc, f"only {size} bytes — likely incomplete")
        else:
            r.ok(f"{doc}  ({size:,} bytes)")


# ---------- section 6: tests -----------------------------------------------

def check_tests(r: Report):
    r.section("Test Suite (offline)")
    try:
        out = subprocess.run(
            [sys.executable, "-m", "pytest", "tests/", "-q",
             "-m", "not integration", "--no-header"],
            cwd=str(_ROOT), capture_output=True, text=True, timeout=120,
        )
        tail = (out.stdout or "").strip().splitlines()[-1] if out.stdout else ""
        if out.returncode == 0:
            r.ok(f"pytest: {tail}")
        else:
            r.fail("pytest", tail or f"exit {out.returncode}")
    except Exception as e:
        r.warn("pytest", f"could not run: {e}")


