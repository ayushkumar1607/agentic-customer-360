def check_files(r: Report):
    r.section("Files & Directories")

    for f in REQUIRED_FILES:
        p = _ROOT / f
        if p.exists():
            size = p.stat().st_size
            if size == 0:
                r.warn(f, "exists but is EMPTY")
            else:
                r.ok(f"{f}  ({size:,} bytes)")
        else:
            r.fail(f, "MISSING")

    for d in SOFT_DIRS:
        p = _ROOT / d
        if p.exists():
            r.ok(f"{d}/  (dir)")
        else:
            r.warn(f"{d}/", "missing — may need pipeline run")

    for f in GENERATED_ARTIFACTS:
        p = _ROOT / f
        if p.exists() and p.stat().st_size > 0:
            r.ok(f"{f}  ({p.stat().st_size:,} bytes)")
        elif p.exists():
            r.warn(f"{f}", "exists but empty — run pipeline")
        else:
            r.warn(f"{f}", "not yet generated — run pipeline")

    for f in OPTIONAL_ARTIFACTS:
        p = _ROOT / f
        if p.exists() and p.stat().st_size > 0:
            r.ok(f"{f}  ({p.stat().st_size:,} bytes)")
